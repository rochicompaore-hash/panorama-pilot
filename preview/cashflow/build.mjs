import { build, transform } from "esbuild";
import fs from "node:fs/promises";
import path from "node:path";
import vm from "node:vm";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import tailwindcss from "tailwindcss";
import autoprefixer from "autoprefixer";

const root = path.dirname(fileURLToPath(import.meta.url));
const frontend = path.resolve(root, "../../frontend");
const dist = path.join(root, "dist");
const dataPath = path.join(root, "data/scenarios.json");
const ids = ["overdue", "uncertified", "undated", "boundary"];

let scenarios;
try {
  scenarios = JSON.parse(await fs.readFile(dataPath, "utf8"));
} catch (error) {
  throw new Error("Dati di prova mancanti o JSON non valido: eseguire generate_data.py prima della build.", { cause: error });
}
if (!Array.isArray(scenarios) || scenarios.length !== ids.length ||
    new Set(scenarios.map((scenario) => scenario.id)).size !== ids.length ||
    ids.some((id) => !scenarios.some((scenario) => scenario.id === id)) ||
    scenarios.some((scenario) => typeof scenario.title !== "string" || !scenario.title.trim() ||
      typeof scenario.description !== "string" || !scenario.description.trim() ||
      !scenario.data?.situation_today || !Array.isArray(scenario.data?.daily_projection))) {
  throw new Error("Schema scenari non valido: servono i quattro ID previsti e i payload completi del modulo cassa.");
}

await fs.mkdir(path.join(dist, "assets"), { recursive: true });
const bundle = await build({
  absWorkingDir: root,
  entryPoints: ["src/main.jsx"],
  outfile: path.join(dist, "assets/preview.js"),
  bundle: true,
  minify: true,
  sourcemap: false,
  metafile: true,
  format: "esm",
  platform: "browser",
  target: ["es2020"],
  jsx: "automatic",
  nodePaths: [path.join(root, "node_modules")],
  alias: {
    "@/api/client": path.join(root, "src/api-disabled.js"),
    "@": path.join(frontend, "src"),
  },
  define: { "process.env.NODE_ENV": '"production"' },
});
if (Object.keys(bundle.metafile.inputs).some((name) => name.replaceAll("\\", "/").endsWith("frontend/src/api/client.js"))) {
  throw new Error("Build interrotta: il client API di produzione non deve essere incluso nell’anteprima.");
}

// Use the actual project theme. Resolve its plugin from this isolated package,
// so building the preview does not require installing the entire frontend.
const configPath = path.join(frontend, "tailwind.config.js");
const configModule = { exports: {} };
vm.runInNewContext(await fs.readFile(configPath, "utf8"), {
  module: configModule,
  require: createRequire(import.meta.url),
}, { filename: configPath });
const theme = configModule.exports;
const sourceCss = (await fs.readFile(path.join(frontend, "src/index.css"), "utf8"))
  .replace(/^@import\s+url\(['"]https:\/\/fonts\.googleapis\.com[^\n]+\n?/gm, "");
const shellCss = await fs.readFile(path.join(root, "src/shell.css"), "utf8");
const styled = await postcss([
  tailwindcss({ ...theme, content: [
    path.join(root, "src/**/*.{js,jsx}"),
    path.join(frontend, "src/components/cfo/CashCommandCenter.jsx"),
    path.join(frontend, "src/components/ui/{card,badge}.jsx"),
  ] }),
  autoprefixer({ overrideBrowserslist: [">0.2%", "not dead", "not op_mini all"] }),
]).process(`${sourceCss}\n${shellCss}`, { from: undefined });
const css = await transform(styled.css, { loader: "css", minify: true });
await fs.writeFile(path.join(dist, "assets/preview.css"), css.code);
await fs.writeFile(path.join(dist, "index.html"), `<!doctype html>
<html lang="it">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="robots" content="noindex,nofollow">
  <meta name="description" content="Anteprima del modulo cassa di Panorama Pilot con quattro scenari sintetici verificabili.">
  <title>Panorama Pilot 2 · Verifica previsioni di cassa</title>
  <link rel="stylesheet" href="./assets/preview.css">
</head>
<body><div id="root"></div><script type="module" src="./assets/preview.js"></script></body>
</html>\n`);
await fs.writeFile(path.join(dist, "build-manifest.json"), JSON.stringify({
  component: "frontend/src/components/cfo/CashCommandCenter.jsx#CashCommandCenterView",
  scenarios: scenarios.map(({ id, title, data }) => ({ id, title, today: data.today })),
  data_source: "preview/cashflow/data/scenarios.json generated by the Python cash engine",
  api_enabled: false,
}, null, 2));
console.log(`Anteprima compilata: ${scenarios.length} scenari, interfaccia reale, API disabilitata.`);
